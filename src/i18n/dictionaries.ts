export const toLocale = (value: string | undefined): Locale =>
  (LOCALES as readonly string[]).includes(value ?? '') ? (value as Locale) : DEFAULT_LOCALE;

/** Intl locale: Thai uses the Buddhist calendar and 24h time (Figma TH frames). */
